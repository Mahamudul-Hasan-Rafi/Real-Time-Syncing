SELECT 'ABS' SRC, 'C' CON_ISL,C.CUST_NO,
       C.CUST_CODE,
       DECODE (C.CUST_TYPE,  'CUS', 'Customer',  'AGN', 'Agent')
           CUSTOMER_TYPE,
       C.CUST_TYPE,
       C.FIRST_NAME,
       C.LAST_NAME,
       C.FATHER_NAME,
       C.MOTHER_NAME,
       C.CUST_DOB,
       DECODE(C.GENDER,'M','Male','F','Female') GENDR,
       C.GENDER,
       DECODE(c.maritual_status,'SNG','Single','MAR','Married') Mar_status,
       c.maritual_status,
       C.SPOUSE_NAME,
       c.no_of_children,
       c.aml_sts,
       c.token_no,
       c.aml_sending_date,
       c.no_of_dependant,
       c.mail_id,
       c.other_bank,
       c.other_bank_acc_no,
       c.income_person,
       c.income_male,
       c.income_female,
       c.relation_with_guardian,
       c.check_by,
       c.check_date,
       c.remark,
       C.SON,
       C.DAUGHTER,
       C.MOBILE_NO,
       C.RELIGIOUS_CODE,
       C.OCCUPATION_CODE,
       (SELECT CODDES FROM EMOB.STCODMAS WHERE HARCOD='OCC' AND SOFCOD=C.OCCUPATION_CODE) OCCUPATION,
       C.ANNUAL_INCOME,
       C.CUST_STATUS,
       C.MEDIA,
       C.LIVE_PERIOD,
       C.HOME_TYPE,
       C.LAST_EDUCATION,
       (SELECT CODDES FROM EMOB.STCODMAS WHERE HARCOD='EDT' AND SOFCOD=C.LAST_EDUCATION) EDUCATION,
       C.FAMILY_GUARDIAN,
       C.CREATE_BY,
       C.REVIEW_STATUS,
       (SELECT json_arrayagg (
                   json_object ('document_id' VALUE DOCUMENT_ID,
                                'document_type' VALUE DOCUMENT_TYPE,
                                'document_no' VALUE DOCMENT_NO,
                                'issue_date' VALUE ISSUE_DATE,
                                'issue_place' VALUE ISSUE_PLACE,
                                'expire_date' VALUE EXPIRE_DATE,
                                'create_by' VALUE CREATE_BY,
                                'create_date' VALUE CREATE_DATE))
          FROM EMOB.MB_DOCUMENT_MST
         WHERE CUST_NO = C.CUST_NO)
           DOC,
       (SELECT json_arrayagg (
                   json_object ('address_id' VALUE a.address_id,
                                'address_type' VALUE a.address_type,
                                'district' VALUE d.district_name,
                                'upazilla' VALUE u.upazila_name,
                                'union' VALUE un.union_name,
                                'post_code' VALUE a.post_code,
                                'village' VALUE a.village,
                                'ward' VALUE a.ward_no,
                                'road_no' VALUE a.road_no,
                                'holding_no' VALUE a.holding_no,
                                'create_date' VALUE a.CREATE_DATE,
                                'create_by' VALUE a.CREATE_by))    Address
          FROM EMOB.MB_ADDRESS_MST  a,
               emob.district_info   d,
               emob.upazila_info    u,
               emob.union_info      un
         WHERE     a.ref_NO = C.CUST_NO
               AND a.district_code = d.district_code
               AND d.district_code = u.district_code
               AND un.district_code = d.district_code
               AND un.upazila_code = u.upazila_code
               AND a.upazila_code = u.upazila_code
               AND a.union_code = un.union_code)
           Address,
           (SELECT  json_arrayagg(json_object ('ac_id' VALUE op.AC_ID,
                    'cust_no' VALUE op.cust_no,
                    'name' VALUE cs.first_name||' '||cs.last_name,
                    'status' VALUE   op.status,
                    'create_by' VALUE op.create_by,
                    'inactive_by' VALUE op.inactive_by,
                   'inactive_date' VALUE op.inactive_date,
                    'create_date' VALUE op.CREATE_DATE)) operator
  FROM EMOB.MB_ACCOUNT_OPERATOR op,emob.mb_customer_mst cs
  WHERE op.ac_id=A.AC_ID
  AND cs.cust_no=op.CUST_NO
) OPERATOR,
 (SELECT  json_arrayagg(json_object ('nominee_id' VALUE nm.nominee_id,
                    'ac_id' VALUE nm.ac_id,
                    'nominee_name' VALUE nm.nominee_name,
                    'father_name' VALUE   nm.father_name,
                    'mother_name' VALUE nm.mother_name,
                    'relation' VALUE nm.relation,
                   'nom_percent' VALUE nm.nom_percent,
                    'nom_type' VALUE nm.nom_type,
                     'docment_no' VALUE nm.docment_no,
                      'dob' VALUE nm.dob,
                    'document_type' VALUE nm.document_type) returning clob) nominee
  FROM EMOB.nominee_mst nm
  WHERE nm.AC_ID=A.AC_ID
) NOMINEE,
       C.AGN_TYPE,
       C.REF_AGN,
       C.AGENT_POINT_ID,
       F.POINT_NAME,
       F.AREA_NAME,
       (SELECT CATEGORY_NAME FROM EMOB.ST_POINT_CATEGORY CP WHERE CP.point_category_id=F.POINT_CATEGORY_ID) POINT_CATEGORY,
       DECODE(F.LOCATION_TYPE,'U','Urban','R','Rural') LOCATION_TYPE,
       A.BRANCH_CODE,
       A.AC_TYPE_ID,
       p.full_desc,
       P.SHORT_DESC,
       P.DEP_NATURE,
       p.ac_type,
       p.nature,
       A.AC_ID,
       A.AC_NO,
       A.AC_TITLE,
       A.OPEN_DATE,
       A.CLOSE_DATE,
       A.ALLTRN,
       A.SECTOR_CODE,
       A.SECURITY_CODE,
       A.ECONOMY_CODE,
       a.comp_type,
       a.debit_enable_by,
       a.debit_enable_date,
       a.initial_amt,
       A.AC_STATUS,
       A.CREATE_BY AC_CREATE_BY,
       A.CREATE_DATE,
       A.FINAL_CHECK,
       A.FINAL_CHECK_DATE,
       A.AC_NATURE,
       DECODE(A.AC_NATURE,'S','Single','J','Joint','C','Company') ACCOUNT_NATURE,
       A.OPR_INS,
       (SELECT INS_DESC FROM EMOB.ST_OPERATING_INSTRUCTION SO WHERE SO.OPR_INS=A.OPR_INS) OPERATING_INS,
       A.CLOSE_BY,
       A.LIEN_MARK,
       A.POINT_ID AC_POINT_ID,
       A.EKYC_TYPE
  FROM EMOB.MB_ACCOUNT_MST   A,
       EMOB.MB_CUSTOMER_MST  C,
       EMOB.ST_AGENT_POINT   F,
       EMOB.MB_PRODUCT_MST   P
 WHERE     A.CUST_NO = C.CUST_NO
       AND C.AGENT_POINT_ID = F.POINT_ID(+)
       AND A.POINT_ID = F.POINT_ID(+)
       AND A.AC_TYPE_ID = P.AC_TYPE_ID
