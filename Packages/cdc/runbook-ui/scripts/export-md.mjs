// Writes ../runbook.md from data/runbook.ts, so the UI and the file shared with the DBA cannot drift apart.
// Run: npm run export-md   (Node 22.18 or newer, it reads the .ts files directly)
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { defaultValues, toMarkdown } from "../data/render.ts";

const target = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "runbook.md");
writeFileSync(target, toMarkdown(defaultValues(), "Generated by runbook-ui: npm run export-md. Edit runbook-ui/data/runbook.ts, not this file.") + "\n");
console.log("written", target);
